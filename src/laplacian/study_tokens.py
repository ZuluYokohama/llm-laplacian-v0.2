"""Immutable, offline CPU tokenization of hash-verified study partitions."""

from __future__ import annotations

import argparse
from contextlib import ExitStack
import hashlib
import heapq
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import re
import struct
import sys

from . import study_data

SPLITS = tuple(study_data.SPLIT_WEIGHTS)
TOKEN_POLICY = "gpt2_story_eos_u16le_v1"
TOKENIZER_REVISION = "607a30d783dfa663caf39e06633721c8d4cfcd7e"
TOKENIZER_SHA256 = "8414cab924d8b9b33013f0d221c5862f365ee9be39c5c2bfae8a5a9e970478a6"
DEFAULT_TOKENIZER_JSON = Path.home() / ".cache/huggingface/hub/models--gpt2/snapshots" / TOKENIZER_REVISION / "tokenizer.json"
VOCAB_SIZE = 50257
EOS_ID = 50256
HEX_SHA = re.compile(r"[0-9a-f]{64}")


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")


def file_record(path):
    path = Path(path).resolve()
    return {"path": str(path), "bytes": path.stat().st_size, "sha256": study_data.sha256_file(path)}


def verify_snapshot(records):
    for expected in records:
        if file_record(expected["path"]) != expected:
            raise RuntimeError(f"input changed while tokenizing: {expected['path']}")


def dependency_identity():
    """Hash actual installed distribution files, not only declared wheel hashes.

    Generated bytecode is excluded; RECORD, Python sources, and native libraries
    are included. These are the two directly used third-party distributions.
    """
    packages, files = {}, []
    for name in ("pyarrow", "tokenizers"):
        distribution = importlib.metadata.distribution(name)
        if not distribution.files:
            raise RuntimeError(f"dependency has no installed-file inventory: {name}")
        declared = {}
        for relative in sorted(distribution.files, key=str):
            if "__pycache__" in relative.parts or relative.suffix == ".pyc":
                continue
            record = file_record(distribution.locate_file(relative))
            files.append(record)
            declared[str(relative).replace("\\", "/")] = {key: record[key] for key in ("bytes", "sha256")}
        packages[name] = {"version": distribution.version, "files": declared}
    return {"packages": packages, "files": files,
            "sha256": hashlib.sha256(canonical(packages)).hexdigest()}


def partition_inputs(folder):
    folder = Path(folder).resolve()
    path = folder / "manifest.json"
    manifest_record = file_record(path)
    manifest = json.loads(path.read_text(encoding="utf-8"))
    if manifest.get("complete") is not True or manifest.get("tokenized") is not False:
        raise ValueError("a complete, untokenized partition manifest is required")
    if manifest.get("schema_version") != 1 or manifest.get("policy") != study_data.POLICY:
        raise ValueError("unsupported partition policy/schema")
    if type(manifest.get("seed")) is not int or manifest.get("weights_per_10000") != study_data.SPLIT_WEIGHTS:
        raise ValueError("invalid partition seed or weights")
    counts = manifest.get("story_counts", {})
    if set(counts) != set(SPLITS) or any(type(counts[split]) is not int or counts[split] <= 0 for split in SPLITS):
        raise ValueError("all four study splits must have positive story counts")
    if manifest.get("unique_stories") != sum(counts.values()):
        raise ValueError("partition story counts do not sum to unique_stories")
    for field in ("source_rows", "duplicates_removed", "empty_rows_removed"):
        if type(manifest.get(field)) is not int or manifest[field] < 0:
            raise ValueError(f"invalid partition count: {field}")
    if manifest["source_rows"] != sum(counts.values()) + manifest["duplicates_removed"] + manifest["empty_rows_removed"]:
        raise ValueError("partition source-row accounting mismatch")
    if set(manifest.get("files", {})) != {f"{split}.jsonl" for split in SPLITS}:
        raise ValueError("partition manifest must bind exactly four split JSONLs")
    records = [manifest_record]
    for filename, expected in manifest["files"].items():
        record = file_record(folder / filename)
        if record["sha256"] != expected:
            raise ValueError(f"partition file hash mismatch: {filename}")
        records.append(record)
    sources = manifest.get("sources")
    if not isinstance(sources, list) or not sources:
        raise ValueError("partition sources must be a nonempty list")
    paths = []
    for source in sources:
        path = Path(source["path"])
        if not path.is_absolute():
            raise ValueError("partition source paths must be absolute")
        record = file_record(path)
        if record["sha256"] != source.get("sha256") or record["bytes"] != source.get("bytes"):
            raise ValueError(f"Arrow source hash/size mismatch: {path}")
        records.append(record)
        paths.append(Path(record["path"]))
    if len(paths) != len(set(paths)):
        raise ValueError("duplicate Arrow source path")
    return manifest, records, paths


def split_refs(handle, split, manifest):
    previous, count = None, 0
    for line in handle:
        row = json.loads(line)
        source_index, row_index = row.get("source_index"), row.get("row_index")
        if type(source_index) is not int or not 0 <= source_index < len(manifest["sources"]):
            raise ValueError("invalid partition source index")
        if type(row_index) is not int or row_index < 0:
            raise ValueError("invalid partition row index")
        key = (source_index, row_index)
        if previous is not None and key <= previous:
            raise ValueError(f"partition row references are not strictly sorted: {split}")
        for field in ("story_id", "text_sha256"):
            if not isinstance(row.get(field), str) or HEX_SHA.fullmatch(row[field]) is None:
                raise ValueError(f"invalid partition {field}")
        if study_data.assigned_split(row["story_id"], manifest["seed"]) != split:
            raise ValueError("story reference is assigned to the wrong split")
        previous, count = key, count + 1
        yield key, split, row
    if count != manifest["story_counts"][split]:
        raise ValueError(f"partition row count mismatch: {split}")


def merged_refs(handles, manifest):
    streams = [split_refs(handles[split], split, manifest) for split in SPLITS]
    previous = None
    for reference in heapq.merge(*streams, key=lambda item: item[0]):
        if previous is not None and reference[0] <= previous:
            raise ValueError("duplicate row reference across study partitions")
        previous = reference[0]
        yield reference


def load_tokenizer(path):
    """Load exact pinned local bytes; this API performs no Hub/network lookup."""
    from tokenizers import Tokenizer

    if study_data.sha256_file(path) != TOKENIZER_SHA256:
        raise ValueError("tokenizer JSON does not match the pinned GPT-2 snapshot")
    tokenizer = Tokenizer.from_file(str(path))
    tokenizer.no_padding()
    tokenizer.no_truncation()
    return tokenizer


def write_json(path, value):
    with Path(path).open("xb") as handle:
        handle.write(json.dumps(value, sort_keys=True, indent=2, allow_nan=False).encode("utf-8") + b"\n")
        handle.flush()
        os.fsync(handle.fileno())


def prepare(partitions, output, tokenizer_json=DEFAULT_TOKENIZER_JSON, *, tokenizer=None):
    """Produce a fresh token bundle; injected tokenizers are non-production fixtures."""
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    provisional = {"schema_version": 1, "policy": TOKEN_POLICY, "complete": False}
    write_json(output / "manifest.json", provisional)
    try:
        partition, inputs, sources = partition_inputs(partitions)
        tokenizer_record = file_record(tokenizer_json)
        inputs.append(tokenizer_record)
        injected = tokenizer is not None
        if not injected:
            tokenizer = load_tokenizer(tokenizer_json)
        if tokenizer.get_vocab_size() != VOCAB_SIZE or tokenizer.token_to_id("<|endoftext|>") != EOS_ID:
            raise ValueError("tokenizer vocabulary/EOS does not match GPT-2")
        if tokenizer.padding is not None or tokenizer.truncation is not None:
            raise ValueError("tokenizer padding and truncation must be disabled")
        code = [file_record(__file__), file_record(study_data.__file__)]
        dependencies = dependency_identity()
        runtime = {"python": platform.python_version(), "implementation": platform.python_implementation(),
                   "executable": file_record(sys.executable)}
        inputs.extend(code + dependencies["files"] + [runtime["executable"]])
        counts, token_counts = dict.fromkeys(SPLITS, 0), dict.fromkeys(SPLITS, 0)
        source_rows = 0
        with ExitStack() as stack:
            handles = {split: stack.enter_context((Path(partitions) / f"{split}.jsonl").open("r", encoding="utf-8")) for split in SPLITS}
            token_files = {split: stack.enter_context((output / f"{split}.u16").open("xb")) for split in SPLITS}
            indices = {split: stack.enter_context((output / f"{split}.stories.jsonl").open("x", encoding="utf-8", newline="\n")) for split in SPLITS}
            references = merged_refs(handles, partition)
            reference = next(references, None)
            for source_index, row_index, text in study_data.arrow_rows(sources):
                source_rows += 1
                key = (source_index, row_index)
                if reference is None:
                    continue
                if reference[0] < key:
                    raise ValueError(f"partition references a missing Arrow row: {reference[0]}")
                if reference[0] != key:
                    continue
                _, split, row = reference
                if not isinstance(text, str) or hashlib.sha256(text.encode("utf-8")).hexdigest() != row["text_sha256"]:
                    raise ValueError(f"story text hash mismatch at {key}")
                if study_data.story_identity(text) != row["story_id"]:
                    raise ValueError(f"normalized story identity mismatch at {key}")
                ids = tokenizer.encode(text, add_special_tokens=False).ids
                if not ids or any(type(token) is not int or not 0 <= token < VOCAB_SIZE or token > 65535 for token in ids):
                    raise ValueError(f"invalid/overflow token ID at {key}")
                ids = [*ids, EOS_ID]
                token_files[split].write(struct.pack(f"<{len(ids)}H", *ids))
                record = {**row, "offset": token_counts[split], "length": len(ids)}
                indices[split].write(json.dumps(record, sort_keys=True) + "\n")
                counts[split] += 1
                token_counts[split] += len(ids)
                if sum(counts.values()) % 10000 == 0:
                    print(f"PROGRESS study_tokens stories={sum(counts.values())} tokens={sum(token_counts.values())}", flush=True)
                reference = next(references, None)
            if reference is not None:
                raise ValueError(f"partition references a missing Arrow row: {reference[0]}")
            if source_rows != partition["source_rows"] or counts != partition["story_counts"]:
                raise ValueError("Arrow/source or selected-story row counts do not match the partition manifest")
            for handle in [*token_files.values(), *indices.values()]:
                handle.flush()
                os.fsync(handle.fileno())
        files = {}
        for split in SPLITS:
            for filename in (f"{split}.u16", f"{split}.stories.jsonl"):
                record = file_record(output / filename)
                files[filename] = {key: record[key] for key in ("sha256", "bytes")}
            if files[f"{split}.u16"]["bytes"] != token_counts[split] * 2:
                raise RuntimeError("token file size does not match uint16 token count")
        verify_snapshot(inputs)
        if dependency_identity() != dependencies:
            raise RuntimeError("dependency inventory changed while tokenizing")
        manifest = {
            **provisional, "complete": True, "production_ready": not injected,
            "partition_manifest": inputs[0], "partition_policy": partition["policy"],
            "partition_seed": partition["seed"], "sources": partition["sources"],
            "partition_files": partition["files"], "source_rows": source_rows,
            "story_counts": counts, "token_counts": token_counts, "files": files,
            "dtype": "<u2", "offset_unit": "tokens", "length_includes_eos": True,
            "tokenizer": {"mode": "injected_test_double" if injected else "pinned_gpt2",
                          "revision": None if injected else TOKENIZER_REVISION, "file": tokenizer_record,
                          "vocab_size": VOCAB_SIZE, "eos_id": EOS_ID, "add_special_tokens": False,
                          "append_eos_per_story": True, "padding": False, "truncation": False},
            "code": code, "dependencies": dependencies, "runtime": runtime,
            "limitations": "Inherits exact normalized-content partitions; does not establish semantic deduplication or historical non-exposure. Injected tokenizers are never production-ready.",
        }
        temporary = output / "manifest.complete.tmp"
        write_json(temporary, manifest)
        temporary.replace(output / "manifest.json")
        return manifest
    except BaseException as exc:
        write_json(output / "failure.json", {**provisional, "error": f"{type(exc).__name__}: {exc}"})
        raise


def validate_bundle(manifest_path):
    """Validate a production bundle and its bound inputs; accepts manifest.json."""
    manifest_path = Path(manifest_path).resolve()
    if manifest_path.name != "manifest.json" or not manifest_path.is_file():
        raise ValueError("an existing token-bundle manifest.json path is required")
    identity = file_record(manifest_path)
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if (manifest.get("schema_version") != 1 or manifest.get("policy") != TOKEN_POLICY
            or manifest.get("complete") is not True or manifest.get("production_ready") is not True):
        raise ValueError("a complete production token bundle is required")
    tokenizer = manifest.get("tokenizer", {})
    if (tokenizer.get("mode") != "pinned_gpt2" or tokenizer.get("revision") != TOKENIZER_REVISION
            or tokenizer.get("vocab_size") != VOCAB_SIZE or tokenizer.get("eos_id") != EOS_ID
            or tokenizer.get("add_special_tokens") is not False or tokenizer.get("append_eos_per_story") is not True
            or tokenizer.get("padding") is not False or tokenizer.get("truncation") is not False
            or tokenizer.get("file", {}).get("sha256") != TOKENIZER_SHA256):
        raise ValueError("token bundle does not bind the pinned GPT-2 policy")
    if manifest.get("dtype") != "<u2" or manifest.get("offset_unit") != "tokens" or manifest.get("length_includes_eos") is not True:
        raise ValueError("unsupported token/offset format")
    partition_record = manifest["partition_manifest"]
    if file_record(partition_record["path"]) != partition_record:
        raise ValueError("bound partition manifest changed")
    partition, _, _ = partition_inputs(Path(partition_record["path"]).parent)
    for field, parent_field in (("partition_policy", "policy"), ("partition_seed", "seed"),
                                ("story_counts", "story_counts"), ("sources", "sources"),
                                ("partition_files", "files"), ("source_rows", "source_rows")):
        if manifest.get(field) != partition[parent_field]:
            raise ValueError(f"token bundle/partition mismatch: {field}")
    if set(manifest.get("token_counts", {})) != set(SPLITS):
        raise ValueError("token counts must cover exactly four study splits")
    expected_files = {filename for split in SPLITS for filename in (f"{split}.u16", f"{split}.stories.jsonl")}
    if set(manifest.get("files", {})) != expected_files:
        raise ValueError("token bundle must bind exactly eight output files")
    for filename, expected in manifest["files"].items():
        actual = file_record(manifest_path.parent / filename)
        if {key: actual[key] for key in ("bytes", "sha256")} != expected:
            raise ValueError(f"token bundle file hash/size mismatch: {filename}")
    for split in SPLITS:
        count = manifest["token_counts"][split]
        if type(count) is not int or count < manifest["story_counts"][split] * 2:
            raise ValueError("invalid token count")
        if manifest["files"][f"{split}.u16"]["bytes"] != count * 2:
            raise ValueError("uint16 byte length/token count mismatch")
    dependencies = manifest["dependencies"]
    if set(dependencies.get("packages", {})) != {"pyarrow", "tokenizers"} or not dependencies.get("files"):
        raise ValueError("missing direct dependency provenance")
    declared = set()
    for package in dependencies["packages"].values():
        if not package.get("version") or not package.get("files"):
            raise ValueError("incomplete dependency inventory")
        declared.update((record["sha256"], record["bytes"]) for record in package["files"].values())
    if declared != {(record["sha256"], record["bytes"]) for record in dependencies["files"]}:
        raise ValueError("dependency inventory/file binding mismatch")
    if dependencies.get("sha256") != hashlib.sha256(canonical(dependencies["packages"])).hexdigest():
        raise ValueError("dependency identity digest mismatch")
    if {Path(record["path"]).name for record in manifest.get("code", [])} != {"study_tokens.py", "study_data.py"}:
        raise ValueError("missing tokenization/partition source-code identity")
    verify_snapshot([tokenizer["file"], *manifest["code"], *dependencies["files"], manifest["runtime"]["executable"]])
    # Refuse races during validation rather than returning a stale identity.
    verify_snapshot([identity, partition_record])
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--partitions", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tokenizer-json", type=Path, default=DEFAULT_TOKENIZER_JSON)
    args = parser.parse_args()
    result = prepare(args.partitions, args.output, args.tokenizer_json)
    print(json.dumps({"complete": result["complete"], "production_ready": result["production_ready"],
                      "token_counts": result["token_counts"], "output": str(args.output)}))


if __name__ == "__main__":
    main()
