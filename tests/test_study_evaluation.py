@pytest.mark.parametrize("length", [1, 2, 127, 128, 129, 256, 257, 258, 400, 513, 1024])
def test_windows_cover_every_target_once_with_bounded_prefix(length):
    targets = []
    for start, end, first in evaluation.window_bounds(length):
        assert 0 <= start < end < length and end - start <= 256
        assert start < first <= end
        targets.extend(range(first, end + 1))
    assert targets == list(range(1, length))


@pytest.mark.parametrize("batch_size", [1, 2, 8])
def test_uniform_oracle_short_uneven_long_and_padding_excluded(batch_size):
    tokens, stories, _ = fixture_stories()
    rows = evaluation.evaluate_stories(UniformModel(poison_padding=True), tokens, stories,
                                      context=4, stride=2, batch_size=batch_size, pad_id=0)
    assert [row["valid_targets"] for row in rows] == [1, 3, 9]
    assert [row["windows"] for row in rows] == [1, 1, 4]
    for row in rows:
        assert row["summed_nll"] == pytest.approx((row["length"] - 1) * math.log(7), abs=2e-6)


def test_context_dependent_logits_match_independent_hand_enumerated_oracle():
    tokens, stories, sequences = fixture_stories()
    rows = evaluation.evaluate_stories(PrefixModel(), tokens, stories, context=4, stride=2, batch_size=5)
    # Exact prefix starts for targets1..9 of the ten-token story. These are
    # hand-enumerated, rather than generated by the production window helper.
    prefix_starts = [[0], [0, 0, 0], [0, 0, 0, 0, 2, 2, 4, 4, 5]]
    for sequence, starts, row in zip(sequences, prefix_starts, rows):
        expected = 0.0
        for target, start in enumerate(starts, 1):
            scale = (sum(sequence[start:target]) % 3 + 1) / 3
            logits = [scale * category for category in range(7)]
            expected += math.log(math.fsum(math.exp(value) for value in logits)) - logits[sequence[target]]
        assert row["summed_nll"] == pytest.approx(expected, abs=3e-6)


