class UniformModel(torch.nn.Module):
    def __init__(self, vocab=7, poison_padding=False):
        super().__init__()
        self.vocab = vocab
        self.poison_padding = poison_padding

    def forward(self, inputs):
        logits = torch.zeros(*inputs.shape, self.vocab, device=inputs.device)
        if self.poison_padding:
            logits[inputs == 0] = float("nan")
        return {"logits": logits}


class PrefixModel(torch.nn.Module):
    def forward(self, inputs):
        scale = (inputs.cumsum(dim=1) % 3 + 1).float() / 3
        return {"logits": scale[..., None] * torch.arange(7, device=inputs.device).float()}


def fixture_stories():
    sequences = [[1, 6], [2, 3, 4, 6], [1, 2, 3, 4, 5, 1, 2, 3, 4, 6]]
    stories, flattened = [], []
    for index, sequence in enumerate(sequences):
        stories.append({"story_id": str(index), "offset": len(flattened), "length": len(sequence)})
        flattened.extend(sequence)
    return np.array(flattened, dtype="<u2"), stories, sequences


