def test_checkpoint_changed_during_input_validation_is_not_rebound(bound_fixture, monkeypatch):
    original = study_train.file_record
    calls = []

    def mutate_on_recheck(path):
        if Path(path).resolve() == bound_fixture.checkpoint.resolve():
            calls.append(True)
            if len(calls) == 3:
                with Path(path).open("ab") as handle:
                    handle.write(b" ")
        return original(path)

    monkeypatch.setattr(study_train, "file_record", mutate_on_recheck)
    with pytest.raises(ValueError, match="bound file changed"):
        evaluation.evaluate(bound_fixture)
    assert len(calls) >= 3
    assert not (bound_fixture.output / "metrics.json").exists()


def test_success_sidecar_failure_cannot_promote_complete_result(bound_fixture, monkeypatch):
    original = evaluation.write_metrics

    def fail_pending(path, payload):
        if Path(path).name == "metrics.pending.json":
            Path(path).write_text(json.dumps(payload))
            raise OSError("simulated sidecar write failure")
        return original(path, payload)

    monkeypatch.setattr(evaluation, "write_metrics", fail_pending)
    with pytest.raises(OSError, match="sidecar write"):
        evaluation.evaluate(bound_fixture)
    assert not (bound_fixture.output / "metrics.json").exists()
    assert json.loads((bound_fixture.output / "error.json").read_text())["complete"] is False


