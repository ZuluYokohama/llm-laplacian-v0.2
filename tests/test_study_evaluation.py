def test_real_causal_model_batch_padding_matches_single_window_scoring():
    tokens, stories, _ = fixture_stories()
    torch.manual_seed(17)
    model = SpectralTransformer(vocab=7, m=1, d_model=16, n_layers=1, context=4)
    single = evaluation.evaluate_stories(model, tokens, stories, context=4, stride=2, batch_size=1, pad_id=6)
    batched = evaluation.evaluate_stories(model, tokens, stories, context=4, stride=2, batch_size=5, pad_id=6)
    for a, b in zip(single, batched):
        assert a["valid_targets"] == b["valid_targets"]
        assert a["summed_nll"] == pytest.approx(b["summed_nll"], abs=2e-6)


