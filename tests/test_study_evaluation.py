@pytest.mark.parametrize("mutation", ["checkpoint", "manifest", "tokens", "sources"])
def test_input_or_source_mutation_during_scoring_never_completes(bound_fixture, monkeypatch, mutation):
    original = evaluation.evaluate_stories

    def mutate(*args, **kwargs):
        rows = original(*args, **kwargs)
        if mutation == "sources":
            monkeypatch.setattr(evaluation, "sources", lambda: [])
        else:
            path = {"checkpoint": bound_fixture.checkpoint, "manifest": bound_fixture.token_manifest,
                    "tokens": bound_fixture.token_manifest.parent / "development.u16"}[mutation]
            # Do not resize an open memmap on Windows; overwrite existing bytes.
            if mutation == "tokens":
                with path.open("r+b") as handle:
                    handle.write(b"\x05\x00")
            else:
                with path.open("ab") as handle:
                    handle.write(b" ")
        return rows

    monkeypatch.setattr(evaluation, "evaluate_stories", mutate)
    with pytest.raises(ValueError, match="changed"):
        evaluation.evaluate(bound_fixture)
    assert not (bound_fixture.output / "metrics.json").exists()
    assert json.loads((bound_fixture.output / "error.json").read_text())["complete"] is False


