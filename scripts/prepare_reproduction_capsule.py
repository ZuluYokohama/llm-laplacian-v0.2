"""Copy a bounded CPU reproduction into a new directory with raw source hashes.

No corpus, model checkpoint, credentials, environment variables, or unrelated
user files are copied. The pinned GPT-2 JSON is copied for the real-tokenizer
smoke; all corpus data are generated by tests. Wheels are referenced, not copied.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = [
    "test_fractional_gradients.py", "test_loss_optimization.py", "test_resume.py",
    "test_reproducibility.py", "test_study_budget.py", "test_study_train.py",
    "test_study_data.py", "test_study_tokens.py", "test_token_audit.py",
    "test_claims.py", "test_citation_sources.py", "test_gpu_resume_gate.py",
    "test_fractional_cutoff_cpu.py", "test_study_evaluation.py",
    "test_study_rate.py",
    "test_benchmark_optimization.py", "test_gpu_diagnostic_gates.py",
]


def prepare(output, tokenizer_json):
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    paths = list((ROOT / "src/laplacian").glob("*.py"))
    paths += [ROOT / "tests" / name for name in TESTS]
    paths += [ROOT / name for name in [
        "pyproject.toml", "scripts/study_budget.py", "scripts/audit_study_tokens.py",
        "scripts/validate_claims.py", "scripts/bind_paper.py", "paper/fetch_references.py",
        "scripts/check_gpu_resume.py", "scripts/prepare_reproduction_capsule.py",
        "scripts/check_fractional_cutoff_cpu.py", "scripts/evaluate_study.py",
        "scripts/benchmark_study_rate.py",
        "scripts/benchmark_optimization.py", "scripts/check_gpu_numerics.py",
        "scripts/check_fractional_sensitivity.py",
        "paper/planning/FRACTIONAL_POLICY.md",
        "paper/planning/environment_20261021/observed.json",
        "paper/planning/environment_20261021/wheel_inventory.json",
        "paper/planning/environment_20261021/requirements-windows-cp312-hashed.txt",
        "runs/optimization_20261021/baseline_losses.py",
    ]]
    files = {}
    for path in paths:
        relative = path.relative_to(ROOT)
        data = path.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        if hashlib.sha256(target.read_bytes()).hexdigest() != digest:
            raise RuntimeError(f"Copied file differs: {relative}")
        files[relative.as_posix()] = digest
    for relative, expected in files.items():
        if hashlib.sha256((ROOT / relative).read_bytes()).hexdigest() != expected:
            raise RuntimeError(f"Source changed during capture: {relative}")
    tokenizer = Path(tokenizer_json).read_bytes()
    tokenizer_digest = hashlib.sha256(tokenizer).hexdigest()
    if tokenizer_digest != "8414cab924d8b9b33013f0d221c5862f365ee9be39c5c2bfae8a5a9e970478a6":
        raise ValueError("Capsule requires the pinned GPT-2 tokenizer bytes")
    (output / "assets").mkdir()
    (output / "assets/gpt2-tokenizer.json").write_bytes(tokenizer)
    if hashlib.sha256((output / "assets/gpt2-tokenizer.json").read_bytes()).hexdigest() != tokenizer_digest:
        raise RuntimeError("Copied tokenizer differs")
    files["assets/gpt2-tokenizer.json"] = tokenizer_digest
    manifest = {"complete": True, "scope": "Bounded local CPU reproduction inputs; not external replication",
                "tests": ["tests/" + name for name in TESTS], "files": files,
                "test_environment": {"CUDA_VISIBLE_DEVICES": "-1", "LAPLACIAN_TOKENIZER_JSON": "assets/gpt2-tokenizer.json"},
                "limitations": "Python/Windows runtime and external wheelhouse are required; no actual corpus or model study is reproduced."}
    (output / "capsule.json").write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8", newline="\n")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tokenizer-json", type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.output, args.tokenizer_json)
    print(json.dumps({"complete": result["complete"], "files": len(result["files"]), "test_files": len(result["tests"])}))
